/** Heavier forms of the letters whose bold would otherwise fill in. */
const BOLD_SOURCES: Record<string, string> = {
  "m": "........|........|#######.|##.##.##|##.##.##|##.##.##|##.##.##",
  "w": ".......|.......|##...##|##...##|##.#.##|#######|.##.##.",
  "M": "##...##|###.###|#######|##.#.##|##...##|##...##|##...##",
  "W": "##...##|##...##|##...##|##.#.##|#######|###.###|##...##",
};

export const GLYPHS: Record<string, Glyph> = Object.fromEntries(
  Object.entries(SOURCES).map(([character, source]) => [character, glyph(source)]),
);

export const BOLD_GLYPHS: Record<string, Glyph> = Object.fromEntries(
  Object.entries(BOLD_SOURCES).map(([character, source]) => [character, glyph(source)]),
);

/** The box drawn for a character the font does not have. */
export const MISSING_GLYPH = glyph("#####|#...#|#...#|#...#|#...#|#...#|#####");

const PICTOGRAPH = /\p{Extended_Pictographic}|\p{Regional_Indicator}/u;

export function isPictograph(grapheme: string) {
  return PICTOGRAPH.test(grapheme);
}

const segmenter = new Intl.Segmenter("en", { granularity: "grapheme" });

export function graphemesOf(text: string) {
  return [...segmenter.segment(text.replace(/\u00a0/g, " "))].map(({ segment }) => segment);
}

/** Horizontal advance of one grapheme, in font pixels. */
export function glyphAdvance(grapheme: string, bold = false) {
  if (grapheme === " ") return 3;
  if (bold && BOLD_GLYPHS[grapheme]) return BOLD_GLYPHS[grapheme].width + 1;
  const known = GLYPHS[grapheme];
  if (known) return known.width + 1 + (bold ? 1 : 0);
  if (isPictograph(grapheme)) return 11;
  return MISSING_GLYPH.width + 1 + (bold ? 1 : 0);
}

/** Width of a line in font pixels, without the gap after its last glyph. */
export function measureText(text: string, bold = false) {
  const width = graphemesOf(text).reduce((sum, grapheme) => sum + glyphAdvance(grapheme, bold), 0);
  return Math.max(0, width - 1);
}

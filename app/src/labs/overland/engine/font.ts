// The Overland typeface: an original proportional bitmap font, drawn for
// this lab. Pure data and metrics; drawing lives in text-draw.ts.

export interface Glyph {
  width: number;
  rows: string[];
}

function glyph(source: string): Glyph {
  const rows = source.split("|");
  return { width: rows[0].length, rows };
}

